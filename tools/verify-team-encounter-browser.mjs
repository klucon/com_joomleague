import fs from 'node:fs';
import assert from 'node:assert/strict';
import {firefox} from '/mnt/disk-a/dev/uklid/2026-09-19/office-browser-tests/node_modules/playwright-core/index.mjs';
const credentials = fs.readFileSync('/mnt/disk-a/pswd/joomla62-local.md', 'utf8');
const password = credentials.match(/^Password:\s*(.+)$/m)?.[1]?.replaceAll('`', '').trim();
assert.ok(password, 'Local credentials missing.');
const output = '/mnt/disk-a/dev/com_joomleague_6-2-0/tests/artifacts/team-encounter';
fs.mkdirSync(output, {recursive: true});
const browser = await firefox.launch({executablePath: '/opt/playwright/firefox-1532/firefox/firefox', headless: true});
try {
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, recordVideo: {dir: output, size: {width: 1440, height: 1000}}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://joomla62.local/administrator/', {waitUntil: 'networkidle'});
  await page.locator('#mod-login-username').fill('admin');
  await page.locator('#mod-login-password').fill(password);
  await Promise.all([page.waitForNavigation({waitUntil: 'networkidle'}), page.locator('button[type=submit]').click()]);
  const edit = 'http://joomla62.local/administrator/index.php?option=com_joomleague&view=matchresult&match_id=1';
  await page.goto(edit, {waitUntil: 'networkidle'});
  assert.equal(await page.locator('select[name$="[encounter_format]"]').count(), 4);
  assert.equal(await page.locator('select[name$="[encounter_format]"]').nth(3).inputValue(), 'doubles');
  assert.equal(await page.locator('select[name*="[nominations]"] option:checked').filter({hasText: /Player/}).count(), 10);
  await page.screenshot({path: output + '/editor-desktop.png', fullPage: true});
  const form = page.locator('#adminForm');
  await Promise.all([page.waitForNavigation({waitUntil: 'networkidle'}), form.evaluate(el => { el.querySelector('input[name="task"]').value = 'matchresult.apply'; el.requestSubmit(); })]);
  assert.equal(await page.locator('select[name$="[encounter_format]"]').count(), 4);
  assert.equal(await page.locator('select[name*="[nominations]"] option:checked').filter({hasText: /Player/}).count(), 10);
  assert.ok(!(await page.locator('body').innerText()).includes('Save failed'));
  const noToken = await context.request.post('http://joomla62.local/administrator/index.php?option=com_joomleague', {form: {task: 'matchresult.apply', match_id: '1'}});
  assert.equal(noToken.status(), 403, 'Result write without CSRF token was not rejected.');
  await page.goto('http://joomla62.local/index.php?option=com_joomleague&view=eventreport&event_id=1', {waitUntil: 'networkidle'});
  assert.ok((await page.locator('body').innerText()).includes('Team A'));
  await page.screenshot({path: output + '/report-desktop.png', fullPage: true});
  assert.ok(await page.locator('a').filter({hasText: /Player [12] Team [AB]/}).count() >= 4, (await page.locator('body').innerText()).slice(0, 2000));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: output + '/report-mobile.png', fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
  assert.deepEqual(errors, []);
  await context.close();
  console.log('Browser encounter OK: login, saved nominations, doubles, frontend person links, desktop/mobile and no JavaScript errors.');
} finally { await browser.close(); }

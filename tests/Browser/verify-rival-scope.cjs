const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

module.exports = async (browser, base, app) => {
    const fixture = JSON.parse(execFileSync('docker', ['exec', app, 'cat', '/tmp/jl-rival-scope.json'], {encoding:'utf8'}));
    const checks = [];
    const component = page => page.locator('.com-joomleague-clubrivals');
    const summary = page => component(page).locator('table').first();
    const details = page => page.locator('table[data-rival-events]');
    const openMenu = async page => {
        await page.goto(base+'/index.php',{waitUntil:'networkidle'});
        await page.getByRole('link',{name:'Rival scope settings',exact:true}).click();
        await page.waitForLoadState('networkidle');
    };
    for (const width of [1440,390]) {
        const context = await browser.newContext({viewport:{width,height:1000}});
        const page = await context.newPage(); const errors = []; const dialogs = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('dialog', async dialog => {dialogs.push(dialog.message()); await dialog.dismiss();});
        await openMenu(page);
        assert.equal(await page.locator('#clubrivals-team').inputValue(),String(fixture.teams.own_first));
        assert.equal(await summary(page).locator('tbody tr').count(),2,'Opponent squads merged');
        await page.getByRole('link',{name:'Opponent first',exact:true}).click();await page.waitForLoadState('networkidle');
        assert.equal(await details(page).locator('tbody tr').count(),25);
        assert.match(await details(page).locator('tbody tr').first().innerText(),/02\.10\.2026/);
        assert.equal(await page.locator('[data-rival-breakdown]').count(),3);
        assert.match(await page.locator('[data-rival-breakdown="venue"]').innerText(),/Home[\s\S]*16/);
        assert.match(await page.locator('[data-rival-breakdown="venue"]').innerText(),/Away[\s\S]*16/);
        assert.match(await page.locator('[data-rival-breakdown="competition"]').innerText(),/League 4 <img src=x onerror=alert\(1\)>/);
        assert.equal(await component(page).locator('img').count(),0,'Competition title injected markup');
        const total = await summary(page).locator('tbody tr').first().locator('td').first().innerText();
        assert.equal(total.trim(),'32');
        const next = page.locator('a[href*="detail_limitstart=25"]').first();
        assert(await next.count(),'Missing bounded detail navigation');
        await next.click();await page.waitForLoadState('networkidle');
        assert.equal(await details(page).locator('tbody tr').count(),7);
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu));
        assert.equal(await page.locator('#clubrivals-team').inputValue(),String(fixture.teams.own_first));
        assert.equal((await summary(page).locator('tbody tr').first().locator('td').first().innerText()).trim(),'32','Page changed aggregate');
        assert.equal(await page.locator('[data-rival-breakdown]').count(),3);
        await page.screenshot({path:path.join(process.env.JL_R1_ARTIFACTS,`${process.env.JL_R1_DRIVER}-rival-scope-${width}.png`),fullPage:true});
        await details(page).locator('tbody th a').first().click();await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('.com-joomleague-eventreport').count(),1,'History link failed');
        await openMenu(page);
        await summary(page).locator('thead a[href*="sort=played"]').click();await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu));
        await page.locator('#clubrivals-search').fill('Opponent reserve');
        await component(page).locator('form button[type=submit]').click();await page.waitForLoadState('networkidle');
        assert.equal(await summary(page).locator('tbody tr').count(),1,'Opponent team-name search failed');
        assert.match(await summary(page).innerText(),/Opponent reserve/);
        await component(page).locator('form a.btn-outline-secondary').click();await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('#clubrivals-team').inputValue(),String(fixture.teams.own_first));
        await page.locator('#clubrivals-team').selectOption('0');
        await component(page).locator('form button[type=submit]').click();await page.waitForLoadState('networkidle');
        assert.equal(await summary(page).locator('tbody tr').count(),3,'Own squads merged in team mode');
        assert.match(await summary(page).innerText(),/Own reserve/);
        const bounds=await component(page).evaluate(el=>({right:el.getBoundingClientRect().right,width:document.documentElement.clientWidth}));
        assert(bounds.right<=bounds.width+1,'Component exceeds viewport');
        assert.doesNotMatch(await component(page).innerText(),/COM_JOOMLEAGUE_|Fatal error|SQLSTATE/);
        assert.deepEqual(errors,[]);assert.deepEqual(dialogs,[]);
        checks.push({width,teamPairs:true,breakdowns:true,compactDates:true,pagingTotals:true,menuContext:true,teamSearch:true,escapedLabels:true,eventLink:true});
        await context.close();
    }
    const admin = await browser.newContext(); const page = await admin.newPage();
    await page.goto(base+'/administrator/',{waitUntil:'networkidle'});
    await page.locator('#mod-login-username').fill('admin');await page.locator('#mod-login-password').fill(process.env.JL_R1_PASSWORD);
    await Promise.all([page.waitForNavigation({waitUntil:'networkidle'}),page.locator('#form-login button[type=submit]').click()]);
    const edit=base+'/administrator/index.php?option=com_menus&task=item.edit&id='+fixture.menu;
    const save=async values=>{
        await page.goto(edit,{waitUntil:'networkidle'});
        assert.doesNotMatch(await page.locator('#item-form').innerText(),/COM_JOOMLEAGUE_/,'Menu labels untranslated');
        const fields=await page.locator('#item-form').evaluate(form=>[...new FormData(form)].filter(([,value])=>typeof value==='string'));
        const pairs=[...fields.filter(([key])=>!(key in values)&&key!=='task'),...Object.entries(values),['task','item.apply']];
        const action=new URL(await page.locator('#item-form').getAttribute('action'),page.url()).href;
        const response=await admin.request.post(action,{data:new URLSearchParams(pairs).toString(),headers:{'content-type':'application/x-www-form-urlencoded'},maxRedirects:0});
        assert([302,303].includes(response.status()));
        await page.goto(edit,{waitUntil:'networkidle'});
        for(const [name,value]of Object.entries(values)){
            const field=page.locator('[name="'+name+'"]');
            const selected=await field.count()===1?field:page.locator('[name="'+name+'"]:checked');
            assert.equal(await selected.inputValue(),value,'Native menu setting not retained: '+name);
        }
    };
    await save({'jform[params][rival_grouping]':'club','jform[params][rival_date_format]':'iso','jform[params][show_rival_breakdowns]':'0','jform[request][team_id]':'0'});
    const guest=await browser.newContext();const publicPage=await guest.newPage();
    await openMenu(publicPage);
    assert.equal(await summary(publicPage).locator('tbody tr').count(),1);
    assert.equal((await summary(publicPage).locator('tbody tr').first().locator('td').first().innerText()).trim(),'34');
    await publicPage.getByRole('link',{name:'Rival scope opponent club',exact:true}).click();await publicPage.waitForLoadState('networkidle');
    assert.match(await details(publicPage).locator('tbody tr').first().innerText(),/2026-10-04/);
    assert.equal(await publicPage.locator('[data-rival-breakdown]').count(),0);
    await save({'jform[params][rival_grouping]':'team','jform[params][rival_date_format]':'locale','jform[params][show_rival_breakdowns]':'1','jform[request][team_id]':String(fixture.teams.own_first)});
    await openMenu(publicPage);await publicPage.getByRole('link',{name:'Opponent first',exact:true}).click();await publicPage.waitForLoadState('networkidle');
    assert.match(await details(publicPage).locator('tbody tr').first().innerText(),/October/);
    assert.equal(await publicPage.locator('[data-rival-breakdown]').count(),3);
    checks.push({nativeMenuSaveReopen:true,clubAggregate:true,isoDates:true,localeDates:true,breakdownToggle:true});
    await guest.close();await admin.close();
    fs.writeFileSync(path.join(process.env.JL_R1_ARTIFACTS,process.env.JL_R1_DRIVER+'-rival-scope-browser.json'),JSON.stringify({passed:true,checks},null,2));
};

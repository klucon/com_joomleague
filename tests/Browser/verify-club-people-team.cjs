const assert = require('node:assert/strict');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

module.exports = async (browser, base, checks) => {
    const fixture = JSON.parse(execFileSync('docker', ['exec', process.env.JL_R1_APP, 'cat', '/tmp/jl-people-team.json'], {encoding:'utf8'}));
    const menuLink = page => page.getByRole('link', {name:'Club members by team', exact:true});
    const table = page => page.locator('.com-joomleague-clubpeople table');
    const filter = page => page.locator('.com-joomleague-clubpeople form');
    const submit = async page => {
        await Promise.all([page.waitForNavigation({waitUntil:'networkidle'}), filter(page).locator('button[type=submit]').click()]);
    };
    for (const width of [1440,390]) {
        const context = await browser.newContext({viewport:{width,height:1000}});
        const page = await context.newPage(); const errors = []; const dialogs = [];
        page.on('pageerror', e => errors.push(e.message));
        page.on('dialog', async dialog => {dialogs.push(dialog.message()); await dialog.dismiss();});
        await page.goto(base+'/index.php', {waitUntil:'networkidle'});
        await menuLink(page).click(); await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('#clubpeople-team').inputValue(), String(fixture.first_team), 'Menu default team did not apply');
        assert.equal(await table(page).locator('tbody tr').count(),25);
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu_id));
        await table(page).locator('a[href*="sort=appearances"]').click(); await page.waitForLoadState('networkidle');
        await table(page).locator('a[href*="sort=appearances"]').click(); await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('#clubpeople-team').inputValue(),String(fixture.first_team),'Sorting lost team');
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu_id),'Sorting lost menu context');
        await page.locator('a[href*="start=25"]').first().click(); await page.waitForLoadState('networkidle');
        assert.equal(await table(page).locator('tbody tr').count(),5,'Paging crossed selected squad');
        assert.equal(await page.locator('#clubpeople-team').inputValue(),String(fixture.first_team));
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu_id),'Paging lost menu context');
        await page.locator('#clubpeople-team').selectOption(String(fixture.reserve_team)); await submit(page);
        assert.equal(await table(page).locator('tbody tr').count(),6,'Front-end team selection did not apply');
        const reserveRow = table(page).locator('tbody tr').first();
        assert.match(await reserveRow.innerText(),/SquadPerson00/);
        assert.equal((await reserveRow.locator('td').nth(1).innerText()).trim(),'1','Appearances include first squad');
        assert.equal((await reserveRow.locator('td').nth(2).innerText()).trim(),'1','Metrics include first squad');
        assert.match(await reserveRow.locator('td').last().innerText(),/2023/,'History includes another squad membership dates');
        assert.equal(await filter(page).locator('img').count(),0,'Team name injected markup');
        assert.match(await page.locator('#clubpeople-team option:checked').innerText(),/<img src=x onerror=alert\(1\)>/);
        await page.screenshot({path:path.join(process.env.JL_R1_ARTIFACTS,`${process.env.JL_R1_DRIVER}-clubpeople-team-${width}.png`),fullPage:true});
        await page.locator('#clubpeople-search').fill('SquadPerson34'); await submit(page);
        assert.equal(await table(page).locator('tbody tr').count(),1);
        assert.match(await table(page).innerText(),/SquadPerson34/);
        await filter(page).locator('a.btn-outline-secondary').click(); await page.waitForLoadState('networkidle');
        assert.equal(await page.locator('#clubpeople-team').inputValue(),String(fixture.first_team),'Reset lost menu default team');
        assert.equal(await page.locator('input[name=Itemid]').inputValue(),String(fixture.menu_id),'Reset lost menu context');
        await page.locator('#clubpeople-team').selectOption('0'); await submit(page);
        await Promise.all([page.waitForNavigation({waitUntil:'networkidle'}),page.locator('#clubpeople-limit').selectOption('50')]);
        assert.equal(await table(page).locator('tbody tr').count(),35,'Club view duplicates shared members or omits a squad');
        await page.goto(base+'/index.php?'+new URLSearchParams({option:'com_joomleague',view:'clubpeople',club_id:fixture.club_id,filter_team_id:fixture.foreign_team,Itemid:fixture.menu_id}),{waitUntil:'networkidle'});
        assert.equal(await table(page).count(),0,'Forged team parameter exposed foreign club');
        assert.doesNotMatch(await page.locator('.com-joomleague-clubpeople').innerText(),/SquadPerson|COM_JOOMLEAGUE_/);
        assert.deepEqual(errors,[]); assert.deepEqual(dialogs,[]);
        checks.push({width,memberTeamDefault:true,memberTeamSortingPaging:true,memberTeamMetrics:true,memberTeamSearchReset:true,clubMemberDeduplication:true,escapedTeamLabel:true,foreignTeamRejected:true});
        await context.close();
    }
    const context = await browser.newContext(); const page = await context.newPage();
    await page.goto(base+'/administrator/',{waitUntil:'networkidle'});
    await page.locator('#mod-login-username').fill('admin');
    await page.locator('#mod-login-password').fill(process.env.JL_R1_PASSWORD);
    await Promise.all([page.waitForNavigation({waitUntil:'networkidle'}),page.locator('#form-login button[type=submit]').click()]);
    const editUrl = base+'/administrator/index.php?option=com_menus&task=item.edit&id='+fixture.menu_id;
    await page.goto(editUrl,{waitUntil:'networkidle'});
    const name = 'jform[request][team_id]';
    assert.equal(await page.locator('select[name="'+name+'"]').inputValue(),String(fixture.first_team));
    assert.doesNotMatch(await page.locator('#item-form').innerText(),/COM_JOOMLEAGUE_/,'Untranslated menu form field');
    const fields = await page.locator('#item-form').evaluate(form=>[...new FormData(form)].filter(([,value])=>typeof value==='string'));
    const values = [...fields.filter(([key])=>key!==name&&key!=='task'),[name,String(fixture.reserve_team)],['task','item.apply']];
    const action = new URL(await page.locator('#item-form').getAttribute('action'),page.url()).href;
    const response = await context.request.post(action,{data:new URLSearchParams(values).toString(),headers:{'content-type':'application/x-www-form-urlencoded'},maxRedirects:0});
    assert([302,303].includes(response.status()),'Native default team save failed');
    await page.goto(editUrl,{waitUntil:'networkidle'});
    assert.equal(await page.locator('select[name="'+name+'"]').inputValue(),String(fixture.reserve_team),'Menu team was not persisted');
    const guest = await browser.newContext(); const guestPage = await guest.newPage();
    await guestPage.goto(base+'/index.php',{waitUntil:'networkidle'});
    await menuLink(guestPage).click(); await guestPage.waitForLoadState('networkidle');
    assert.equal(await guestPage.locator('#clubpeople-team').inputValue(),String(fixture.reserve_team));
    assert.equal(await table(guestPage).locator('tbody tr').count(),6,'Saved default team not applied publicly');
    checks.push({nativeMemberTeamSaveReopen:true,publicMemberTeamUpdated:true});
    await guest.close(); await context.close();
};
